-- Bank warehouse DDL / views
CREATE TABLE BANK_DW.CUSTOMER_DIM (
    ACCOUNT_NO  VARCHAR2(12) PRIMARY KEY,
    CUSTOMER_ID VARCHAR2(18),
    SEGMENT     VARCHAR2(10)
);

CREATE TABLE BANK_DW.ACCOUNT (
    ACCOUNT_NO  VARCHAR2(12) PRIMARY KEY,
    BALANCE     NUMBER(15,2),
    STATUS      VARCHAR2(2)
);

CREATE VIEW BANK_DW.V_ACTIVE_ACCOUNT AS
    SELECT ACCOUNT_NO, BALANCE
    FROM   BANK_DW.ACCOUNT
    WHERE  STATUS = 'A';

CREATE TABLE BANK_DW.GOLD_SEGMENT AS
    SELECT c.ACCOUNT_NO, d.SEGMENT, SUM(c.AMOUNT) AS TOTAL
    FROM   CARDS_CLEAN c
    JOIN   BANK_DW.CUSTOMER_DIM d ON c.ACCOUNT_NO = d.ACCOUNT_NO
    GROUP  BY c.ACCOUNT_NO, d.SEGMENT;
